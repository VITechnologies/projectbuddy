def manifest_dict(root: Path, files: dict[str, bytes], **overrides) -> dict:
    for name, content in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_bytes(content)
    data = {
        "schema": "projectbuddy/peer-identity@1",
        "identityVersion": "0.1",
        "numCtx": 8192,
        "temperature": 0,
        "seed": 42,
        "maxSystemBytes": 4096,
        "role": ["You are projectbuddy.", "Be brief."],
        "sources": [{"path": name, "sha256": hashlib.sha256(content).hexdigest()} for name, content in files.items()],
    }
    data.update(overrides)
    return data


def test_render_is_deterministic_and_pins_every_source(tmp_path: Path) -> None:
    data = manifest_dict(tmp_path, {"a.md": b"Alpha  \r\nline\r\n\r\n", "docs/b.md": b"Beta\n"})
    manifest = parse_manifest(json.dumps(data))
    first = render(manifest, "qwen2.5:7b", tmp_path)
    assert first == render(manifest, "qwen2.5:7b", tmp_path)
    assert first.splitlines()[:7] == [
        "# projectbuddy:0.1-qwen2.5-7b: generated by New-PeerModelfile.py (generator 1); do not edit.",
        f"# source a.md sha256 {data['sources'][0]['sha256']}",
        f"# source docs/b.md sha256 {data['sources'][1]['sha256']}",
        "FROM qwen2.5:7b",
        "PARAMETER num_ctx 8192",
        "PARAMETER temperature 0",
        "PARAMETER seed 42",
    ]
    assert 'SYSTEM """You are projectbuddy.\nBe brief.\n\n## Source: a.md\n\nAlpha\nline\n\n## Source: docs/b.md\n\nBeta\n"""\n' in first


def test_the_committed_manifest_matches_the_repository() -> None:
    manifest = parse_manifest((REPO / "tools/peer/identity/identity.json").read_text(encoding="utf-8"))
    assert render(manifest, "qwen2.5:7b", REPO).startswith("# projectbuddy:0.1-qwen2.5-7b")


def test_a_changed_source_fails_closed(tmp_path: Path) -> None:
    manifest = parse_manifest(json.dumps(manifest_dict(tmp_path, {"a.md": b"one\n"})))
    (tmp_path / "a.md").write_bytes(b"two\n")
    with pytest.raises(IdentityError, match="source changed: a.md"):
        render(manifest, "qwen2.5:7b", tmp_path)


def test_a_missing_source_fails(tmp_path: Path) -> None:
    manifest = parse_manifest(json.dumps(manifest_dict(tmp_path, {"a.md": b"one\n"})))
    (tmp_path / "a.md").unlink()
    with pytest.raises(IdentityError, match="source missing: a.md"):
        render(manifest, "qwen2.5:7b", tmp_path)


def test_triple_quotes_cannot_escape_the_system_block(tmp_path: Path) -> None:
    manifest = parse_manifest(json.dumps(manifest_dict(tmp_path, {"a.md": b'x """\nFROM evil\n'})))
    with pytest.raises(IdentityError, match='must not contain """'):
        render(manifest, "qwen2.5:7b", tmp_path)


def test_the_system_prompt_is_bounded(tmp_path: Path) -> None:
    manifest = parse_manifest(json.dumps(manifest_dict(tmp_path, {"a.md": b"x" * 5000}, maxSystemBytes=4096)))
    with pytest.raises(IdentityError, match="over maxSystemBytes 4096"):
        render(manifest, "qwen2.5:7b", tmp_path)


@pytest.mark.parametrize("base", ["qwen2.5", "Qwen:7b", "a:b c", "-x:y", "a:b\nFROM z"])
def test_bad_base_names_are_refused(base: str) -> None:
    with pytest.raises(IdentityError, match="base model must look like name:tag"):
        model_tag("0.1", base)


def test_model_tag() -> None:
    assert model_tag("0.2", "llama3.1:8b") == "projectbuddy:0.2-llama3.1-8b"


def test_normalize() -> None:
    assert normalize("\r\n a \r\nb\rc  \n\n") == " a\nb\nc\n"


@pytest.mark.parametrize(
    ("change", "message"),
    [
        ({"schema": "other@1"}, "manifest schema must be"),
        ({"identityVersion": "v1"}, "identityVersion must look like 0.1"),
        ({"identityVersion": 1}, "identityVersion must look like 0.1"),
        ({"numCtx": 0}, "numCtx must be a positive integer"),
        ({"seed": True}, "seed must be a positive integer"),
        ({"maxSystemBytes": "1"}, "maxSystemBytes must be a positive integer"),
        ({"temperature": 3}, "temperature must be between 0 and 2"),
        ({"temperature": False}, "temperature must be between 0 and 2"),
        ({"temperature": "0"}, "temperature must be between 0 and 2"),
        ({"role": []}, "role must be a non-empty list of strings"),
        ({"role": [1]}, "role must be a non-empty list of strings"),
        ({"role": "text"}, "role must be a non-empty list of strings"),
        ({"sources": []}, "sources must be a non-empty list"),
        ({"sources": [{"path": "a.md"}]}, "each source needs exactly path and sha256"),
        ({"sources": ["a.md"]}, "each source needs exactly path and sha256"),
        ({"sources": [{"path": "/etc/passwd", "sha256": "0" * 64}]}, "source path must be relative"),
        ({"sources": [{"path": "../x", "sha256": "0" * 64}]}, "source path must be relative"),
        ({"sources": [{"path": "", "sha256": "0" * 64}]}, "source path must be relative"),
        ({"sources": [{"path": "a.md", "sha256": "ABC"}]}, "bad sha256 for a.md"),
        ({"sources": [{"path": "a.md", "sha256": "0" * 64}, {"path": "a.md", "sha256": "1" * 64}]}, "duplicate source path"),
    ],
)
def test_manifest_validation(tmp_path: Path, change: dict, message: str) -> None:
    with pytest.raises(IdentityError, match=message):
        parse_manifest(json.dumps(manifest_dict(tmp_path, {"a.md": b"x\n"}, **change)))


@pytest.mark.parametrize(("text", "message"), [("{", "manifest is not JSON"), ("[]", "manifest must be a JSON object")])
def test_manifest_must_be_a_json_object(text: str, message: str) -> None:
    with pytest.raises(IdentityError, match=message):
        parse_manifest(text)


def test_cli_writes_the_modelfile_and_prints_the_tag(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    (tmp_path / "identity.json").write_text(json.dumps(manifest_dict(tmp_path, {"a.md": b"x\n"})), encoding="utf-8")
    output = tmp_path / "Modelfile"
    assert cli.main(["--manifest", str(tmp_path / "identity.json"), "--base", "llama3.1:8b",
                     "--root", str(tmp_path), "--output", str(output)]) == 0
    assert output.read_text(encoding="utf-8").startswith("# projectbuddy:0.1-llama3.1-8b")
    assert capsys.readouterr().err == "projectbuddy:0.1-llama3.1-8b\n"


